    private static DiscFragmentItem discFragItem(final String name) {
        final Identifier identifier = MoreDiscs.id(name);
        final ResourceKey<Item> KEY = ResourceKey.create(Registries.ITEM, identifier);
        return (Registry.register(BuiltInRegistries.ITEM, KEY, new DiscFragmentItem(new Item.Properties().setId(KEY).stacksTo(8))));
    }

    private static Item createDisc(final String name, final DiscRarities rarity, final ResourceKey<JukeboxSong> song) {
        MoreDiscs.LOGGER.info(name + " " + rarity);
        String rarityType = switch (rarity) {
            case COMMON -> "common";
            case UNCOMMON -> "uncommon";
            case RARE -> "rare";
            case EPIC -> "epic";
            case LEGENDARY -> "legendary";
            case MYTHIC -> "mythic";
            case VILLAGER -> "villager";
            case WANDER_GEN -> "gen_wandy-t";
            case WANDER_RARE -> "rare_wandy-t";
            case NONE -> "none";
        };
        final Identifier identifier = MoreDiscs.id(name);
        final ResourceKey<Item> KEY = ResourceKey.create(Registries.ITEM, identifier);
        return (Registry.register(BuiltInRegistries.ITEM, KEY, new Item(new Item.Properties().setId(KEY).jukeboxPlayable(song).stacksTo(1)
                .overrideDescription((rarityType.equals("none")? "item.more_discs_rebelspark.%s".formatted(name): "tooltip.more_discs_rebelspark.%s_disc".formatted(rarityType))))));
    }

    private static DiscHolderItemParent createDiscHolder(final String name) {
        final Identifier identifier = MoreDiscs.id(name);
        final ResourceKey<Item> KEY = ResourceKey.create(Registries.ITEM, identifier);
        return (Registry.register(BuiltInRegistries.ITEM, KEY, new DiscHolderItemParent(new Item.Properties().stacksTo(1).setId(KEY))));
    }

